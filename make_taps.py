# make_taps.py - writes resample_taps.h: the filter of both sample-rate converters. 48 -> 44 kHz is 11 up, 12 down; 44 ->
# 48 kHz is 12 up, 11 down: both run at 528 kHz, so one low-pass serves both. 924 taps (84 a phase of 11, 77 of 12),
# windowed sinc, cutoff 20.5 kHz, Kaiser beta 8.5. MIT, Copyright 2026 amnmkkr.
import numpy as np
N, fs, fc = 924, 528000.0, 20500.0
n = np.arange(N) - (N - 1) / 2.0
h = 2 * fc / fs * np.sinc(2 * fc / fs * n) * np.kaiser(N, 8.5)
h /= np.sum(h)          # unity at DC; the converters scale by their up factor
H = np.fft.rfft(h, 1 << 20); f = np.fft.rfftfreq(1 << 20, 1 / fs); db = 20 * np.log10(np.abs(H) + 1e-15)
for x in (1000, 10000, 18000, 19000, 20000, 21000, 22000, 24000, 26000):
    print(x, round(float(db[np.argmin(abs(f - x))]), 2))
print("worst from 22 kHz:", round(float(db[f >= 22000].max()), 1))
with open("resample_taps.h", "w") as o:
    o.write("// resample_taps.h - the low-pass of both sample-rate converters (48 <-> 44 kHz through 528 kHz): 924 taps, windowed\n")
    o.write("// sinc, cutoff 20.5 kHz, Kaiser beta 8.5, unity at DC. Generated by make_taps.py. MIT, Copyright 2026 amnmkkr.\n")
    o.write("#pragma once\nstatic const float kResampleTaps[924] = {\n")
    for i in range(0, N, 6):
        o.write("  " + ", ".join("%.9ef" % v for v in h[i:i + 6]) + ",\n")
    o.write("};\n")
